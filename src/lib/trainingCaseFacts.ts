export function caseBranch(scenario: Pick<Scenario, "id">, variant: number): CaseBranch {
  const category = Number(scenario.id.split("-")[0]);
  if (!Number.isInteger(category) || category < 0 || category >= BRANCHES.length ||
    !Number.isInteger(variant) || variant < 0 || variant >= CASE_VARIANT_COUNT) {
    throw new Error("INVALID_CASE_VARIANT");
  }
  return BRANCHES[category][variant];
}
